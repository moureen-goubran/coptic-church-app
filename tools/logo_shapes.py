"""Writes app/src/lib/logo-shapes.ts from the church logos in app/public/logos.
Run from the project folder after adding or changing a logo: python3 tools/logo_shapes.py
For each logo it records its shape (width / height) and its background colour, taken from the
pixels along its edge, so the card can paint the logo's box in the same colour.
Logos with a see-through edge get no colour and sit on the app's soft fill. The build checks the file is up to date.
Logos that are paintings or photos (listed in FILL) fill their whole box instead, cropped from the top so faces show."""
import glob, os
from collections import Counter
from PIL import Image
FILL = {'nj-holmdel-st-mina-holmdel.webp', 'nj-whippany-st-john-the-beloved-st-mary-magdalene.webp'}
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)

def edge_colour(im):
    w, h = im.size
    px = [im.getpixel((x, y)) for x in range(0, w, max(1, w // 60)) for y in (0, h - 1)]
    px += [im.getpixel((x, y)) for y in range(0, h, max(1, h // 30)) for x in (0, w - 1)]
    if sum(p[3] > 200 for p in px) < len(px) * 0.7: return None  # mostly see-through
    solid = [p for p in px if p[3] > 200]
    # The most common colour (rounded) wins; a photo with no single background gets its average edge.
    top, n = Counter(tuple(c // 8 * 8 for c in p[:3]) for p in solid).most_common(1)[0]
    near = [p for p in solid if all(abs(a - b) < 24 for a, b in zip(p[:3], top))] if n >= len(solid) * 0.4 else solid
    return '#%02x%02x%02x' % tuple(round(sum(p[i] for p in near) / len(near)) for i in range(3))

rows = []
for f in sorted(glob.glob(os.path.join(root, 'app/public/logos/*'))):
    if not f.endswith(('.webp', '.png')): continue
    im = Image.open(f).convert('RGBA'); w, h = im.size
    bg = edge_colour(im)
    rows.append(f'  "/logos/{os.path.basename(f)}": {{ ratio: {round(w / h, 2)}, bg: {"null" if bg is None else repr(bg).replace(chr(39), chr(34))}{", fill: true" if os.path.basename(f) in FILL else ""} }},')
open(os.path.join(root, 'app/src/lib/logo-shapes.ts'), 'w').write(
    '// Generated by tools/logo_shapes.py: run it after adding or changing a logo. Shape is width / height;\n'
    '// bg is the colour along the logo\'s edge (null when the edge is see-through); fill means a painting that fills its box.\n'
    'export const LOGOS: Record<string, { ratio: number; bg: string | null; fill?: boolean }> = {\n' + '\n'.join(rows) + '\n};\n')
print(len(rows), 'logos')
